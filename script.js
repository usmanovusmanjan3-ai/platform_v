// ========================================
// START
// ========================================

startBtn.addEventListener("click", startQuiz);


function startQuiz() {

    playerName =
        playerNameInput.value.trim();

    if (!playerName) {

        playerNameInput.focus();

        playerNameInput.style.borderColor =
            "#ff4d67";

        setTimeout(() => {

            playerNameInput.style.borderColor =
                "";

        }, 1500);

        return;
    }


    // SAVOLLARNI OLISH

    if (selectedCategory === "mixed") {

        questions = [
            ...questionData.uzbekistan,
            ...questionData.temur,
            ...questionData.world,
            ...questionData.ancient
        ];

        shuffleArray(questions);

        questions =
            questions.slice(0, 15);

    } else {

        questions =
            [...questionData[selectedCategory]];

        shuffleArray(questions);

        questions =
            questions.slice(0, 10);
    }


    // RESET

    currentIndex = 0;

    score = 0;

    lives = 3;

    combo = 0;

    bestCombo = 0;

    correctCount = 0;

    wrongCount = 0;

    skippedCount = 0;

    scoreElement.textContent = "0";

    quizPlayerName.textContent =
        playerName;

    categoryName.textContent =
        categoryNames[selectedCategory];

    totalQuestionsElement.textContent =
        questions.length;


    startScreen.classList.add("hidden");

    resultScreen.classList.add("hidden");

    quizScreen.classList.remove("hidden");


    showQuestion();

}


// ========================================
// SAVOLNI KO'RSATISH
// ========================================

function showQuestion() {

    clearInterval(timerInterval);

    answered = false;

    hintUsed = false;

    hintBtn.classList.remove("used");

    hintBtn.disabled = false;


    const question =
        questions[currentIndex];


    currentQuestionElement.textContent =
        currentIndex + 1;

    questionNumber.textContent =
        String(currentIndex + 1).padStart(2, "0");

    questionText.textContent =
        question.question;


    progressBar.style.width =
        ((currentIndex) / questions.length * 100) + "%";


    answersElement.innerHTML = "";


    const letters =
        ["A", "B", "C", "D"];


    question.answers.forEach((answer, index) => {

        const button =
            document.createElement("button");

        button.className = "answer";

        button.innerHTML = `
            <span class="answer-letter">
                ${letters[index]}
            </span>

            ${answer}
        `;

        button.addEventListener(
            "click",
            () => selectAnswer(index, button)
        );

        answersElement.appendChild(button);

    });


    timeLeft = 15;

    updateTimer();

    timerInterval =
        setInterval(() => {

            timeLeft--;

            updateTimer();

            if (timeLeft <= 0) {

                clearInterval(timerInterval);

                timeOut();

            }

        }, 1000);


    comboElement.textContent =
        `🔥 COMBO x${combo}`;

    streakText.textContent =
        combo > 0
            ? `${combo} ta ketma-ket to‘g‘ri javob!`
            : "Ketma-ket to‘g‘ri javoblar";


    // animatsiya

    const card =
        document.querySelector(".question-card");

    card.classList.remove("show");

    void card.offsetWidth;

    card.classList.add("show");

}


// ========================================
// TIMER
// ========================================

function updateTimer() {

    timerElement.textContent =
        timeLeft;

    if (timeLeft <= 5) {

        timerElement.classList.add("danger");

    } else {

        timerElement.classList.remove("danger");

    }

}


// ========================================
// JAVOB BERISH
// ========================================

function selectAnswer(index, button) {

    if (answered) return;

    answered = true;

    clearInterval(timerInterval);


    const question =
        questions[currentIndex];


    const allAnswers =
        document.querySelectorAll(".answer");

    allAnswers.forEach(item => {

        item.classList.add("disabled");

    });


    if (index === question.correct) {

        button.classList.add("correct");

        correctCount++;

        combo++;

        if (combo > bestCombo) {

            bestCombo = combo;

        }


        // BALL HISOBLASH

        let points = 100;

        points += timeLeft * 5;

        points += combo * 10;


        score += points;

        scoreElement.textContent =
            score;


        streakText.textContent =
            `🔥 ${combo} ta ketma-ket! +${points} ball`;


        showCorrectAnswer(question);

    } else {

        button.classList.add("wrong");

        allAnswers[question.correct]
            .classList.add("correct");


        wrongCount++;

        combo = 0;

        loseLife();

        showCorrectAnswer(question);

    }


    setTimeout(() => {

        nextQuestion();

    }, 1700);

}


// ========================================
// TO'G'RI JAVOB
// ========================================

function showCorrectAnswer(question) {

    // kichik notification

    const notification =
        document.createElement("div");

    notification.className =
        "answer-notification";


    if (question.correct !== undefined) {

        notification.textContent =
            question.explanation;

    }


    document.body.appendChild(notification);


    setTimeout(() => {

        notification.remove();

    }, 1600);

}


// ========================================
// LIFE
// ========================================

function loseLife() {

    lives--;

    updateLives();


    if (lives <= 0) {

        setTimeout(() => {

            endQuiz();

        }, 500);

    }

}


function updateLives() {

    if (lives === 3) {

        livesElement.textContent =
            "❤️ ❤️ ❤️";

    } else if (lives === 2) {

        livesElement.textContent =
            "❤️ ❤️ 🖤";

    } else if (lives === 1) {

        livesElement.textContent =
            "❤️ 🖤 🖤";

    } else {

        livesElement.textContent =
            "🖤 🖤 🖤";

    }

}


// ========================================
// TIME OUT
// ========================================

function timeOut() {

    if (answered) return;

    answered = true;

    wrongCount++;

    combo = 0;

    const question =
        questions[currentIndex];


    const allAnswers =
        document.querySelectorAll(".answer");

    allAnswers.forEach(item => {

        item.classList.add("disabled");

    });


    allAnswers[question.correct]
        .classList.add("correct");


    loseLife();


    setTimeout(() => {

        if (lives > 0) {

            nextQuestion();

        }

    }, 1500);

}


// ========================================
// NEXT QUESTION
// ========================================

function nextQuestion() {

    if (lives <= 0) {

        endQuiz();

        return;

    }


    currentIndex++;


    if (currentIndex >= questions.length) {

        endQuiz();

        return;

    }


    showQuestion();

}


