// HINT
// ========================================

hintBtn.addEventListener("click", () => {

    if (answered || hintUsed) return;

    hintUsed = true;

    hintBtn.classList.add("used");

    hintBtn.disabled = true;


    const question =
        questions[currentIndex];


    const answerButtons =
        document.querySelectorAll(".answer");


    const wrongIndexes = [];

    for (let i = 0; i < 4; i++) {

        if (i !== question.correct) {

            wrongIndexes.push(i);

        }

    }


    shuffleArray(wrongIndexes);


    // 2 ta noto'g'ri variantni olib tashlaymiz

    wrongIndexes
        .slice(0, 2)
        .forEach(index => {

            answerButtons[index].style.opacity =
                ".25";

            answerButtons[index].style.pointerEvents =
                "none";

        });


    // hint ishlatilsa ball kamayadi

    score = Math.max(0, score - 20);

    scoreElement.textContent =
        score;

});


